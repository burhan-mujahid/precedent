"""Compile the rulebook into the formats other tools already read.

Precedent is meant to sit underneath whatever agent stack you use, not replace it:

    skill    an Agent Skills folder (SKILL.md + references/rules.md), for Claude, Codex,
             Cursor, Gemini CLI, Hermes and the other agentskills.io clients
    agents   an AGENTS.md / CLAUDE.md section
    parlant  a script that loads every approved rule as a Parlant guideline
    json     machine-readable rulebook

Static exports lose the runtime gates (coverage, grounding, confidence, risk), so each
export tells the agent to escalate when no rule clearly fits and to never act alone on
high-risk rules. For the full gates, run `precedent mcp` and call consult_rulebook.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

from .models import Rule
from .store import Store


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:64] or "rulebook"


def _line(text: object) -> str:
    """One line of inert text: rule text cannot start a new heading, close the AGENTS.md markers,
    or add fields to SKILL.md frontmatter."""
    return " ".join(str(text).split()).replace("<!--", "<! --").replace("-->", "-- >")


def _rule_md(r: Rule) -> str:
    lines = [f"### {_line(r.id)} - {_line(r.title)}  `{r.risk} risk` `v{r.version}`", "",
             f"- **When:** {_line(r.when)}", f"- **Then:** {_line(r.then)}"]
    if r.why:
        lines.append(f"- **Why:** {_line(r.why)}")
    for e in r.exceptions:
        lines.append(f"- **Exception:** {_line(e)}")
    lines.append(f"- Owner: {_line(r.owner or 'unassigned')} | review by {r.review_by or 'n/a'}")
    return "\n".join(lines)


def render_rulebook(store: Store) -> str:
    rules = store.rules("approved")
    name = store.config.get("name")
    out = [f"# {_line(name)} - Rulebook", "",
           f"{len(rules)} approved rules. Generated by Precedent; edit `rules/*.yaml` or go through "
           "`precedent review`, not this file.", ""]
    groups: dict[str, list[Rule]] = {}
    for r in rules:
        groups.setdefault((r.tags or ["general"])[0], []).append(r)
    for tag in sorted(groups):
        out += [f"## {_line(tag).title()}", ""]
        for r in groups[tag]:
            out += [_rule_md(r), ""]
    return "\n".join(out).rstrip() + "\n"


_GUARD = """\
1. Find the rule whose **When** matches the situation. Match on meaning, not keywords.
2. If exactly one rule clearly fits and it is **low** or **medium** risk, do what its **Then** says and
   name the rule id (e.g. "per R-004") in your reasoning or log.
3. If the rule is **high** risk: prepare the action, but ask a human to approve before doing it.
4. If no rule clearly fits, two rules disagree, or an **Exception** might apply: do not improvise.
   Say what you would do, say which rule came closest, and escalate to a human.
5. Never invent a rule, and never treat this file as permission for anything it does not say."""


def to_skill(store: Store, out_dir: Path) -> Path:
    name = _slug(f"{store.config.get('name')}-rulebook")
    skill = Path(out_dir) / name
    (skill / "references").mkdir(parents=True, exist_ok=True)
    rules = store.rules("approved")
    tags = [t for t, _ in Counter(t for r in rules for t in r.tags).most_common(8)]
    desc = (f"Operating rules for {_line(store.config.get('name'))}: how the team handles "
            f"{', '.join(tags) if tags else 'day-to-day situations'}. Use before acting on any business "
            "situation (customers, suppliers, money, data) to find the approved rule or escalate.")
    skill_md = f"""---
name: {name}
description: {json.dumps(_line(desc)[:1000], ensure_ascii=False)}
---

# {_line(store.config.get('name'))} rulebook

These are the approved operating rules for this business, mined from how the team actually
works and approved by a person. Full text: [references/rules.md](references/rules.md)
({len(rules)} rules).

## How to use them

{_GUARD}

## Rule index

""" + "\n".join(f"- **{_line(r.id)}** ({r.risk}) {_line(r.title)}" for r in rules) + "\n"
    (skill / "SKILL.md").write_text(skill_md, encoding="utf-8")
    (skill / "references" / "rules.md").write_text(render_rulebook(store), encoding="utf-8")
    return skill


def to_agents_md(store: Store) -> str:
    rules = store.rules("approved")
    body = "\n\n".join(_rule_md(r) for r in rules)
    return f"""<!-- precedent:begin - generated, do not edit by hand -->
## Operating rules ({_line(store.config.get('name'))})

{_GUARD}

{body}
<!-- precedent:end -->
"""


def to_parlant(store: Store) -> str:
    rules = store.rules("approved")
    def action(r: Rule) -> str:
        return r.then + (" (needs human approval)" if r.risk == "high" else "")

    items = ",\n".join(f"        ({json.dumps(r.when)}, {json.dumps(action(r))})" for r in rules)
    return f'''"""Load the Precedent rulebook into a Parlant agent as guidelines.
Generated by `precedent export parlant`. Usage: python load_guidelines.py
"""
import asyncio
import parlant.sdk as p

GUIDELINES = [
{items}
]


async def main() -> None:
    async with p.Server() as server:
        agent = await server.create_agent(name={json.dumps(store.config.get("name"))},
                                          description="Follows the approved company rulebook.")
        for condition, action in GUIDELINES:
            await agent.create_guideline(condition=condition, action=action)


if __name__ == "__main__":
    asyncio.run(main())
'''


def to_json(store: Store) -> str:
    return json.dumps({"name": store.config.get("name"), "rules": [r.to_dict() for r in store.rules("approved")]},
                      indent=2, ensure_ascii=False)
